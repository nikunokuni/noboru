// 書き方の違いを吸収した比較用のキー
//   全角・半角、旧字（國・嶋 など）、「之」「の」、繰り返し記号（々）、末尾の「命・尊・神・大神・大御神・公・様」の違い
const OLD_CHARS = { 國: '国', 嶋: '島', 齋: '斎', 龍: '竜', 靈: '霊', 榮: '栄', 賣: '売', 豐: '豊', 氣: '気', 姬: '姫' }
const SUFFIX = /(大御神|大明神|大神|之命|之神|命|尊|神|公|様|さま)$/

export function deityKey(name) {
  let s = (name || '').normalize('NFKC').replace(/\s/g, '')
  s = s.replace(/(.)々/g, '$1$1').replace(/./g, (c) => OLD_CHARS[c] || c)
  s = s.replace(/[ァ-ヶ]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60))
  s = s.replace(/[之のノ]/g, '')
  const stripped = s.replace(SUFFIX, '')
  return stripped.length >= 2 ? stripped : s
}

// キー → 代表の表記
const CANONICAL = new Map()
for (const names of DEITIES) {
  for (const n of names) {
    const k = deityKey(n)
    if (!CANONICAL.has(k)) CANONICAL.set(k, names[0])
  }
}

// 代表の表記 → 別の書き方（検索のヒント用）
const ALIASES = new Map(DEITIES.map((names) => [names[0], names.slice(1)]))
export const deityAliases = (canonical) => ALIASES.get(canonical) || []

// 1柱の名前を代表の表記に。辞書になければ書かれたまま（前後の空白は除く）
export function canonicalDeity(name) {
  const t = (name || '').normalize('NFKC').trim()
  if (!t) return ''
  return CANONICAL.get(deityKey(t)) || t
}

// 「須佐之男命、櫛名田比売（クシナダヒメ）」のような文字を1柱ずつに分ける
export function splitDeities(text) {
  return (text || '').normalize('NFKC')
    .split(/[、,，・/／()（）「」『』\s]+|(?:及び|および)/)
    .map((s) => s.trim()).filter(Boolean)
}

// ご祭神の欄の文字をそろえる。同じ神様の重複（「誉田別命（応神天皇）」など）は1つにまとめる
// 戻り値: { names: 代表の表記の配列, text: 「、」でつないだ文字, changed: [{ from, to }] 書き換えたもの }
export function normalizeDeities(text) {
  const names = []
  const changed = []
  for (const raw of splitDeities(text)) {
    const c = canonicalDeity(raw)
    if (c !== raw) changed.push({ from: raw, to: c })
    if (!names.includes(c)) names.push(c)
  }
  return { names, text: names.join('、'), changed }
}

// 検索語に当てはまる神様の代表の表記（辞書にある神様だけ）
export function matchDeityNames(query) {
  const k = deityKey(query)
  if (!k) return []
  const out = []
  for (const names of DEITIES) {
    if (names.some((n) => deityKey(n).includes(k) || n.includes(query.trim()))) out.push(names[0])
  }
  return out
}
