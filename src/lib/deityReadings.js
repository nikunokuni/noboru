const baseReadings = new Map(Object.entries(BASE).map(([name, reading]) => [deityKey(name), reading]))
const KANA_ONLY = /^[ぁ-ゖァ-ヶー・\s]+$/

// ひらがなの読み。わからなければ null（かなだけの名前もフリガナが要らないので null）
export function deityReading(name) {
  const n = (name || '').normalize('NFKC').replace(/\s/g, '')
  if (!n || KANA_ONLY.test(n)) return null
  if (FULL[n]) return FULL[n]
  const canonical = canonicalDeity(n)
  if (DEITY_PROFILES[canonical] && canonical === n) return DEITY_PROFILES[canonical][0]
  for (const [suffix, reading] of SUFFIXES) {
    if (n.length <= suffix.length || !n.endsWith(suffix)) continue
    const base = n.slice(0, -suffix.length)
    if (FULL[base]) return FULL[base] + reading
    const b = baseReadings.get(deityKey(base))
    if (b) return b + reading
  }
  return baseReadings.get(deityKey(n)) || null
}

const toKatakana = (s) => s.replace(/[ぁ-ゖ]/g, (c) => String.fromCharCode(c.charCodeAt(0) + 0x60))

// カタカナのフリガナ（アマテラスオオミカミ）。わからなければ null
export function deityFurigana(name) {
  const r = deityReading(name)
  return r ? toKatakana(r) : null
}
