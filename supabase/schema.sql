CREATE TABLE records (
  id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),  -- 端末側で採番して送る（オフライン再送で二重登録しないため）
  user_id             UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  shrine_id           BIGINT NOT NULL REFERENCES shrines(id) ON DELETE RESTRICT,
  visited_on          DATE NOT NULL DEFAULT CURRENT_DATE,   -- 後から選べる
  emotion_level       INTEGER NOT NULL DEFAULT 50 CHECK (emotion_level BETWEEN 0 AND 100),
  public_memo         TEXT NOT NULL DEFAULT '',
  is_public           BOOLEAN NOT NULL DEFAULT TRUE,
  onsite              BOOLEAN NOT NULL DEFAULT FALSE,       -- 「現地で記録」印（GPSで近くにいた）
  location_accuracy_m INTEGER,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_records_user   ON records(user_id, visited_on DESC);
CREATE INDEX idx_records_shrine ON records(shrine_id, visited_on DESC);
CREATE INDEX idx_records_public_timeline ON records(visited_on DESC, created_at DESC) WHERE is_public;  -- みんなの参拝

-- 非公開メモは別テーブル（records を公開しても読まれないように）
CREATE TABLE record_private_notes (
  record_id    UUID PRIMARY KEY REFERENCES records(id) ON DELETE CASCADE,
  user_id      UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  private_memo TEXT NOT NULL DEFAULT ''
);

-- 写真（Storage バケット 'photos' に保存。パスは <record_id>/<n>.jpg。user_id を含めない）
CREATE TABLE photos (
  id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  record_id  UUID NOT NULL REFERENCES records(id) ON DELETE CASCADE,
  user_id    UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  path       TEXT NOT NULL UNIQUE,
  tag        TEXT NOT NULL DEFAULT 'other'      -- 写っているもの。神社詳細でタグごとに見られる
             CHECK (tag IN ('torii', 'komainu', 'honden', 'goshuin', 'signboard', 'other')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_photos_record ON photos(record_id);

-- ============================================================
-- 3. 情報提供（神社情報の追加・訂正）
--    「最後に提供された内容をすぐ採用し、履歴を残す」方式。いたずらは管理者が元に戻す
-- ============================================================
CREATE TABLE shrine_edits (
  id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  shrine_id  BIGINT NOT NULL REFERENCES shrines(id) ON DELETE CASCADE,
  user_id    UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  field      TEXT NOT NULL CHECK (field IN (
               'address', 'deities', 'benefits', 'shrine_rank',
               'access_note', 'parking', 'goshuin', 'features', 'name_kana',
               'goshuin_note', 'nearest_station', 'nearest_bus_stop',
               'founded', 'annual_festival', 'visiting_hours', 'highlights')),
  value      JSONB NOT NULL,                    -- 文字列 / 文字列配列 / 列挙値
  old_value  JSONB,                             -- 変更前の値（{列名: 値}）。トリガーが入れる。管理者が元に戻すときに使う
  reverted_at TIMESTAMPTZ,                      -- 管理者が元に戻した時刻
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_shrine_edits_shrine  ON shrine_edits(shrine_id, created_at DESC);
CREATE INDEX idx_shrine_edits_created ON shrine_edits(created_at DESC);
CREATE INDEX idx_shrine_edits_user    ON shrine_edits(user_id, created_at DESC);

-- 管理者が確認する申請
--   add  : リストにない神社の追加（管理者が確認して shrines に追加）
--   hide : 境内社・重複・現存しないなど、一覧から外すべき神社の報告（確認して status = 'hidden'）
CREATE TABLE shrine_requests (
  id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id    UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  kind       TEXT NOT NULL DEFAULT 'add' CHECK (kind IN ('add', 'hide')),
  shrine_id  BIGINT REFERENCES shrines(id) ON DELETE CASCADE,   -- hide のとき対象
  name       TEXT NOT NULL,
  lat        DOUBLE PRECISION,
  lng        DOUBLE PRECISION,
  note       TEXT NOT NULL DEFAULT '',
  from_map   BOOLEAN NOT NULL DEFAULT FALSE,                    -- 「記録する」の地図でピンを立てて申請（現地にいた）
  status     request_status NOT NULL DEFAULT 'pending',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  reviewed_at TIMESTAMPTZ                                        -- 承認・却下した時刻
);

-- 管理者（申請の承認・却下と神社一覧ファイルの作り直しができる）
