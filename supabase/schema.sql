-- records の増減で shrines の集計列を更新
CREATE OR REPLACE FUNCTION refresh_shrine_stats(target BIGINT) RETURNS VOID
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  UPDATE shrines s SET
    record_count     = agg.cnt,
    visitor_count    = agg.users,
    first_visited_on = agg.first_on,
    stats_updated_at = NOW()
  FROM (
    SELECT COUNT(*)::INT AS cnt,
           COUNT(DISTINCT user_id)::INT AS users,
           MIN(visited_on) AS first_on
    FROM records WHERE shrine_id = target
  ) agg
  WHERE s.id = target;
END $$;

CREATE OR REPLACE FUNCTION on_record_change() RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF TG_OP IN ('INSERT', 'UPDATE') THEN
    PERFORM refresh_shrine_stats(NEW.shrine_id);
  END IF;
  IF TG_OP IN ('DELETE', 'UPDATE') AND (TG_OP = 'DELETE' OR OLD.shrine_id <> NEW.shrine_id) THEN
    PERFORM refresh_shrine_stats(OLD.shrine_id);
  END IF;
  RETURN NULL;
END $$;

CREATE TRIGGER trg_records_stats
AFTER INSERT OR UPDATE OF shrine_id, visited_on, user_id OR DELETE ON records
FOR EACH ROW EXECUTE FUNCTION on_record_change();

-- 項目ごとに、変更で書き換わる shrines の列
CREATE OR REPLACE FUNCTION shrine_edit_columns(field TEXT) RETURNS TEXT[]
LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE field
    WHEN 'features'         THEN ARRAY['features', 'features_source']
    WHEN 'nearest_station'  THEN ARRAY['nearest_station', 'nearest_station_m', 'nearest_station_by_user']
    WHEN 'nearest_bus_stop' THEN ARRAY['nearest_bus_stop', 'nearest_bus_stop_m', 'nearest_bus_stop_by_user']
    ELSE ARRAY[field]
  END;
$$;

-- 情報提供を shrines に反映（最後に提供された内容を採用）。変更前の値を old_value に残す
CREATE OR REPLACE FUNCTION apply_shrine_edit() RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  txt TEXT := NULLIF(btrim(NEW.value #>> '{}'), '');   -- 文字列の項目。空なら NULL に戻す
BEGIN
  NEW.reverted_at := NULL;
  SELECT jsonb_object_agg(e.key, e.value) INTO NEW.old_value
  FROM shrines s, jsonb_each(to_jsonb(s)) AS e
  WHERE s.id = NEW.shrine_id AND e.key = ANY(shrine_edit_columns(NEW.field));

  UPDATE shrines SET
    address         = CASE WHEN NEW.field = 'address'      THEN txt ELSE address END,
    name_kana       = CASE WHEN NEW.field = 'name_kana'    THEN txt ELSE name_kana END,
    deities         = CASE WHEN NEW.field = 'deities'      THEN txt ELSE deities END,
    shrine_rank     = CASE WHEN NEW.field = 'shrine_rank'  THEN txt ELSE shrine_rank END,
    access_note     = CASE WHEN NEW.field = 'access_note'  THEN txt ELSE access_note END,
    goshuin_note    = CASE WHEN NEW.field = 'goshuin_note' THEN txt ELSE goshuin_note END,
    founded         = CASE WHEN NEW.field = 'founded'         THEN txt ELSE founded END,
    annual_festival = CASE WHEN NEW.field = 'annual_festival' THEN txt ELSE annual_festival END,
    visiting_hours  = CASE WHEN NEW.field = 'visiting_hours'  THEN txt ELSE visiting_hours END,
    highlights      = CASE WHEN NEW.field = 'highlights'      THEN txt ELSE highlights END,
    features        = CASE WHEN NEW.field = 'features'     THEN txt ELSE features END,
    features_source = CASE WHEN NEW.field = 'features'     THEN 'user' ELSE features_source END,
    benefits        = CASE WHEN NEW.field = 'benefits'
                        THEN ARRAY(SELECT jsonb_array_elements_text(NEW.value)) ELSE benefits END,
    parking         = CASE WHEN NEW.field = 'parking' THEN (NEW.value #>> '{}')::parking_status ELSE parking END,
    goshuin         = CASE WHEN NEW.field = 'goshuin' THEN (NEW.value #>> '{}')::goshuin_status ELSE goshuin END,
    -- 駅・バス停：提供された文字（「〇〇駅 徒歩10分」など）をそのまま表示する。空にしたら次の取り込みで OSM の値に戻る
    nearest_station         = CASE WHEN NEW.field = 'nearest_station' THEN txt ELSE nearest_station END,
    nearest_station_m       = CASE WHEN NEW.field = 'nearest_station' THEN NULL ELSE nearest_station_m END,
    nearest_station_by_user = CASE WHEN NEW.field = 'nearest_station' THEN txt IS NOT NULL ELSE nearest_station_by_user END,
    nearest_bus_stop         = CASE WHEN NEW.field = 'nearest_bus_stop' THEN txt ELSE nearest_bus_stop END,
    nearest_bus_stop_m       = CASE WHEN NEW.field = 'nearest_bus_stop' THEN NULL ELSE nearest_bus_stop_m END,
    nearest_bus_stop_by_user = CASE WHEN NEW.field = 'nearest_bus_stop' THEN txt IS NOT NULL ELSE nearest_bus_stop_by_user END,
    updated_at      = NOW()
  WHERE id = NEW.shrine_id;
  RETURN NEW;
END $$;

-- 変更前の値を残すため、追加の前に反映する
CREATE TRIGGER trg_shrine_edits_apply
BEFORE INSERT ON shrine_edits
FOR EACH ROW EXECUTE FUNCTION apply_shrine_edit();

-- ============================================================
-- 集計関数（個人を特定しない数字だけを返す）
-- ============================================================

-- ホームに出す全体の数字
-- recent_visitors: 過去30日（今日を含む）に1社以上参拝したユーザー数
CREATE OR REPLACE FUNCTION get_app_stats() RETURNS JSON
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT json_build_object(
    'recent_visitors', (SELECT COUNT(DISTINCT user_id) FROM records
                         WHERE visited_on BETWEEN CURRENT_DATE - 29 AND CURRENT_DATE),
    'total_shrines',   (SELECT COUNT(*) FROM shrines WHERE status = 'active'),
    'visited_shrines', (SELECT COUNT(*) FROM shrines
                         WHERE status = 'active' AND first_visited_on IS NOT NULL)
  );
$$;

-- 都道府県別の達成率
CREATE OR REPLACE FUNCTION get_prefecture_progress() RETURNS TABLE (
  prefecture TEXT, total BIGINT, visited BIGINT
)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT prefecture,
         COUNT(*),
         COUNT(*) FILTER (WHERE first_visited_on IS NOT NULL)
  FROM shrines WHERE status = 'active'
  GROUP BY prefecture ORDER BY prefecture;
$$;

GRANT EXECUTE ON FUNCTION get_app_stats(), get_prefecture_progress() TO anon, authenticated;
REVOKE EXECUTE ON FUNCTION refresh_shrine_stats(BIGINT) FROM PUBLIC, anon, authenticated;

-- ============================================================
-- 取り込み処理用（scripts/import-shrines.mjs から service_role で呼ぶ）
--   OSM 由来の列は毎回上書き。ユーザーが情報提供できる列は「空のときだけ」埋める
--   駅・バス停は情報提供されたもの（*_by_user）を上書きしない
-- ============================================================
CREATE OR REPLACE FUNCTION import_shrines(rows JSONB) RETURNS INTEGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE n INTEGER;
BEGIN
  INSERT INTO shrines AS s (
    osm_ref, wikidata_id, name, name_kana, prefecture, municipality, locality, address, lat, lng,
    deities, benefits, shrine_rank, nearest_station, nearest_station_m,
    nearest_bus_stop, nearest_bus_stop_m, parking, features, features_source
  )
  SELECT r.osm_ref, r.wikidata_id, r.name, r.name_kana, r.prefecture, r.municipality, r.locality, r.address, r.lat, r.lng,
         r.deities, COALESCE(r.benefits, '{}'), r.shrine_rank, r.nearest_station, r.nearest_station_m,
         r.nearest_bus_stop, r.nearest_bus_stop_m, COALESCE(r.parking, 'unknown'), r.features, r.features_source
  FROM jsonb_to_recordset(rows) AS r(
    osm_ref TEXT, wikidata_id TEXT, name TEXT, name_kana TEXT, prefecture TEXT, municipality TEXT, locality TEXT,
    address TEXT, lat DOUBLE PRECISION, lng DOUBLE PRECISION, deities TEXT, benefits TEXT[],
    shrine_rank TEXT, nearest_station TEXT, nearest_station_m INTEGER, nearest_bus_stop TEXT,
    nearest_bus_stop_m INTEGER, parking parking_status, features TEXT, features_source TEXT)
  ON CONFLICT (osm_ref) DO UPDATE SET
    wikidata_id        = EXCLUDED.wikidata_id,
    name               = EXCLUDED.name,
    prefecture         = EXCLUDED.prefecture,
    municipality       = EXCLUDED.municipality,
    locality           = EXCLUDED.locality,
    lat                = EXCLUDED.lat,
    lng                = EXCLUDED.lng,
    -- 駅・バス停を取らずに取り込んだとき（--shrines-only / --no-transit）は、入っている値を消さない
    nearest_station    = CASE WHEN s.nearest_station_by_user  OR EXCLUDED.nearest_station  IS NULL THEN s.nearest_station    ELSE EXCLUDED.nearest_station END,
    nearest_station_m  = CASE WHEN s.nearest_station_by_user  OR EXCLUDED.nearest_station  IS NULL THEN s.nearest_station_m  ELSE EXCLUDED.nearest_station_m END,
    nearest_bus_stop   = CASE WHEN s.nearest_bus_stop_by_user OR EXCLUDED.nearest_bus_stop IS NULL THEN s.nearest_bus_stop   ELSE EXCLUDED.nearest_bus_stop END,
    nearest_bus_stop_m = CASE WHEN s.nearest_bus_stop_by_user OR EXCLUDED.nearest_bus_stop IS NULL THEN s.nearest_bus_stop_m ELSE EXCLUDED.nearest_bus_stop_m END,
    name_kana          = COALESCE(s.name_kana,   EXCLUDED.name_kana),
    address            = COALESCE(s.address,     EXCLUDED.address),
    deities            = COALESCE(s.deities,     EXCLUDED.deities),
    shrine_rank        = COALESCE(s.shrine_rank, EXCLUDED.shrine_rank),
    benefits           = CASE WHEN cardinality(s.benefits) = 0 THEN EXCLUDED.benefits ELSE s.benefits END,
    parking            = CASE WHEN s.parking = 'unknown' THEN EXCLUDED.parking ELSE s.parking END,
    features           = COALESCE(s.features, EXCLUDED.features),
    features_source    = CASE WHEN s.features IS NULL THEN EXCLUDED.features_source ELSE s.features_source END,
    updated_at         = NOW();
  GET DIAGNOSTICS n = ROW_COUNT;
  RETURN n;
END $$;

REVOKE EXECUTE ON FUNCTION import_shrines(JSONB) FROM PUBLIC, anon, authenticated;

-- ============================================================
-- 管理者用（アプリの「申請の確認」画面から呼ぶ）
-- ============================================================
CREATE OR REPLACE FUNCTION is_admin() RETURNS BOOLEAN
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (SELECT 1 FROM admins WHERE user_id = auth.uid());
$$;

-- 申請を承認・却下する
--   add  を承認: shrine の内容（name, name_kana, prefecture, municipality, address, lat, lng）で shrines に追加
--               地図から申請（from_map）なら、申請した人の参拝記録を作る（参拝日＝申請日、「現地で記録」の印付き、非公開）
--   hide を承認: 対象の神社を status = 'hidden' にする
-- 戻り値は追加・非表示にした神社の id（却下は NULL）
CREATE OR REPLACE FUNCTION review_shrine_request(request_id UUID, approve BOOLEAN, shrine JSONB DEFAULT '{}')
RETURNS BIGINT
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  req shrine_requests;
  target BIGINT;
BEGIN
  IF NOT is_admin() THEN
    RAISE EXCEPTION '管理者だけが実行できます' USING ERRCODE = '42501';
  END IF;
  SELECT * INTO req FROM shrine_requests WHERE id = request_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION '申請が見つかりません'; END IF;
  IF req.status <> 'pending' THEN RAISE EXCEPTION 'この申請は処理済みです'; END IF;

  IF approve AND req.kind = 'add' THEN
    INSERT INTO shrines (name, name_kana, prefecture, municipality, address, lat, lng)
    VALUES (
      COALESCE(NULLIF(btrim(shrine->>'name'), ''), req.name),
      NULLIF(btrim(shrine->>'name_kana'), ''),
      shrine->>'prefecture',
      NULLIF(btrim(shrine->>'municipality'), ''),
      NULLIF(btrim(shrine->>'address'), ''),
      COALESCE((shrine->>'lat')::DOUBLE PRECISION, req.lat),
      COALESCE((shrine->>'lng')::DOUBLE PRECISION, req.lng))
    RETURNING id INTO target;
    IF req.from_map THEN
      INSERT INTO records (user_id, shrine_id, visited_on, onsite, is_public)
      VALUES (req.user_id, target, (req.created_at AT TIME ZONE 'Asia/Tokyo')::DATE, TRUE, FALSE);
    END IF;
  ELSIF approve AND req.kind = 'hide' THEN
    UPDATE shrines SET status = 'hidden', updated_at = NOW() WHERE id = req.shrine_id;
    target := req.shrine_id;
  END IF;

  UPDATE shrine_requests SET
    status      = CASE WHEN approve THEN 'approved' ELSE 'rejected' END::request_status,
    shrine_id   = COALESCE(target, shrine_id),
    reviewed_at = NOW()
  WHERE id = request_id;
  RETURN target;
END $$;

REVOKE EXECUTE ON FUNCTION review_shrine_request(UUID, BOOLEAN, JSONB) FROM PUBLIC, anon;
GRANT  EXECUTE ON FUNCTION review_shrine_request(UUID, BOOLEAN, JSONB) TO authenticated;

